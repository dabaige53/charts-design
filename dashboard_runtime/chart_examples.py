def example_config(code, fixture):
    """Return an explicit synthetic snapshot, never a template for unknown data."""
    return {'code': code, 'title': '合成示例：' + fixture['title'],
            'data': deepcopy(fixture['data']), 'presentation': deepcopy(PRESENTATIONS[code]),
            **{key: fixture[key] for key in ('hasGranularity', 'defaultGranularity') if key in fixture}}
